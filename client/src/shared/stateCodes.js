export const GSTIN_REGEX = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$/;

export function isValidGstinFormat(gstin) {
  if (!gstin || typeof gstin !== 'string') return false;
  const upper = gstin.trim().toUpperCase();
  if (!GSTIN_REGEX.test(upper)) return false;

  const stateCode = upper.slice(0, 2);
  return INDIAN_STATES.some(s => s.code === stateCode);
}

export function getStateCodeFromGstin(gstin) {
  if (!gstin || typeof gstin !== 'string') return null;
  const upper = gstin.trim().toUpperCase();
  if (upper.length >= 2) {
    const code = upper.slice(0, 2);
    if (INDIAN_STATES.some(s => s.code === code)) {
      return code;
    }
  }
  return null;
}
